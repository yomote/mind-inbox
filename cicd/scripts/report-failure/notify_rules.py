#!/usr/bin/env python3
"""通報ステップの「何をするか / どう見せるか」を決める純関数 (Issue #507)。

判定は 2 段:
    1. plan_action()  — Issue をどうするか (decide.py を土台に、**一覧が引けなかった**
       という第 3 の状態を足したもの)
    2. step_verdict() — 通報に失敗したとき step を赤にするか

なぜ純関数に切り出すか:
    「通報が失敗したか」「その失敗で run を赤にしてよいか」は **判定** であって
    シェルの副作用の順番ではない。ここに置いてテストで固定する
    (cicd/CLAUDE.md「判定ロジックをシェルや workflow の中に埋めない」)。
"""

# #507 の原因 (2026-08-17 の deploy 3 run / 32050157344・32048671609・32048667300):
#   デプロイ本体が全部緑なのに通報ステップだけが **1 行も出力を残さず exit 1** し、
#   run 全体を赤にした。旧実装は open Issue の一覧を `EXISTING=$(gh issue list ...)`
#   というコマンド置換で受けており、runner 既定の `bash -e` 下では gh が非ゼロを返した
#   瞬間に step が死ぬ。しかもその gh 呼び出しは標準エラーを /dev/null へ捨てていたので、
#   **何が失敗したのかがログに 1 文字も残らなかった**。2026-08-21 の deploy は同じコードで
#   緑に戻っており、gh の非ゼロは一過性だったが、**一過性の失敗を無言の赤に変換する**
#   構造そのものが欠陥。

